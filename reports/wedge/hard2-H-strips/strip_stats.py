"""strip_stats.py: who makes the floor strips, H boards against crossings.

Reads strips.py's per-step data (scratch) for the v50 C and B records and the
taxonomy's cause labels (tables.md), and writes strip_stats.md with:

1. the floor at the end and at a matched fill (the first step at fill >= 0.30);
2. where the usable floor is lost: per placement, the usable floor it covers
   (occupied) and the usable floor it kills without covering (the strip),
   by rung, item class, pose, shadow outcome, and the killed strip's
   geometry (direction, what bounds it, where it lies relative to the box);
3. the step that takes the last usable floor ("floor gone"): its rung, class,
   pose, the fill and the floor coverage at that moment.

"Usable floor" = free floor a 0.55 x 0.40 m window (+3 cm) still covers;
"dead" = free floor no such window covers (the strips)."""

from __future__ import annotations

import collections
import json
import os
import re
import statistics as stx

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
DATA = "/home/user/inv-H-scratch/data"
TAB = f"{REPO}/reports/wedge/hard2-miss-taxonomy/tables.md"
RESCUE = {
    "physics-resort",
    "count-mode",
    "grid-rescue",
    "grid-rescue-cover",
    "fallback",
    "last-resort",
}


def causes():
    out = {}
    sec = None
    for line in open(TAB):
        if line.startswith("####"):
            sec = line
            continue
        m = re.match(
            r"\| ([bc]-hard2-s\d+) \| (\w+) \| ([\d.]+) \| (\d+)/(\d+) \| (-?\d+) \| (\w+) \| ([^|]*) \| (\w) \|",
            line,
        )
        if m and sec and "every miss" in sec and ("v50 C" in sec or "v50 B" in sec):
            out[m.group(1)] = m.group(9)
    return out


def group_of(e, cz):
    if e["scene"] in cz:
        return cz[e["scene"]]
    if e["margin"] >= 0 and e["stratum"] in ("sample", "stretch"):
        return "X"  # crossing
    return None


def pose_kind(s):
    if not s["floor"]:
        return "raised"
    return "floor-standing" if s["standing"] else "floor-lying"


def arch_kind(s):
    a = s["arch"]
    if a in RESCUE:
        return a
    if s.get("shadow") in ("replaced", "fallback-after-veto", "kept-after-veto"):
        return f"{a} ({s['shadow']})"
    return a


def fmt(x, n=2):
    return f"{x:.{n}f}"


def main():
    cz = causes()
    eps = []
    for rec in ("gate0-hard2", "gate0-hard2-b"):
        for e in json.load(open(f"{DATA}/strips-{rec}.json")):
            g = group_of(e, cz)
            if g is None:
                continue
            e["group"] = g
            eps.append(e)
    groups = ["H", "G", "D", "X"]
    lines = [
        "# Strip formation: H boards against crossings (v50 hard2, C and B)",
        "",
        "Generated by `strip_stats.py` from `strips.py` (commanded boxes of the records `gate0-hard2`, "
        "`gate0-hard2-b`).  Groups: H (no level patch), G (patch sealed from the door), D (soft carpet) from "
        "the taxonomy; X = crossings of the sample and stretch strata.  Areas in m^2 per episode (means); "
        '"usable" floor = covered by a free 0.58 x 0.43 m window; "dead" = free but not usable.',
        "",
    ]
    # ---------------------------------------------------------------- 1
    lines += [
        "## 1. The floor at a matched fill (first step at fill >= 0.30) and at the end",
        "",
        "| group | task | n | floor | at 0.30: free / usable / dead | at end: free / usable / dead | dead at end: narrow-in-y (runs x) / narrow-in-x (runs y) | bound wall-box / box-box / wall-wall | dead width <0.1 / .1-.2 / .2-.3 / .3-.45 / >.45 |",
        "|---|---|---:|---:|---|---|---|---|---|",
    ]
    for g in groups:
        for task in ("C", "B"):
            E = [e for e in eps if e["group"] == g and e["task"] == task]
            if not E:
                continue
            m30 = []
            for e in E:
                s30 = next((s for s in e["steps"] if s["fill"] >= 0.30), None)
                if s30:
                    dn = s30.get("dead_now") or {}
                    m30.append(
                        (s30["free_m2"], s30["usable_floor_m2"], dn.get("area", 0.0))
                    )
            endf = [
                (
                    sum(c["free_m2"] for c in e["end"]),
                    sum(c["usable_m2"] for c in e["end"]),
                    sum(c["dead_m2"] for c in e["end"]),
                )
                for e in E
            ]
            dd = collections.Counter()
            for e in E:
                for c in e["end"]:
                    d = c["dead"]
                    for k in (
                        "runs_x",
                        "runs_y",
                        "bound_wall_box",
                        "bound_box_box",
                        "bound_wall_wall",
                    ):
                        dd[k] += d.get(k, 0.0)
                    for k, v in (d.get("width_hist") or {}).items():
                        dd["w" + k] += v
            tot = max(1e-9, dd["runs_x"] + dd["runs_y"])
            mean = lambda xs, i: stx.mean(x[i] for x in xs) if xs else float("nan")  # noqa: E731
            wk = ["w0-0.1", "w0.1-0.2", "w0.2-0.3", "w0.3-0.45", "w0.45-9"]
            lines.append(
                f"| {g} | {task} | {len(E)} | {fmt(stx.mean(e['floor_m2'] for e in E))} | "
                f"{fmt(mean(m30, 0))} / {fmt(mean(m30, 1))} / {fmt(mean(m30, 2))} (n={len(m30)}) | "
                f"{fmt(mean(endf, 0))} / {fmt(mean(endf, 1))} / {fmt(mean(endf, 2))} | "
                f"{fmt(dd['runs_x'] / tot)} / {fmt(dd['runs_y'] / tot)} | "
                f"{fmt(dd['bound_wall_box'] / tot)} / {fmt(dd['bound_box_box'] / tot)} / {fmt(dd['bound_wall_wall'] / tot)} | "
                + " / ".join(fmt(dd[k] / tot) for k in wk)
                + " |"
            )
    lines.append("")
    # ---------------------------------------------------------------- 2
    lines += [
        "## 2. Where the usable floor goes: occupied by a box, or killed (turned into strips) without being covered",
        "",
        'Per episode means over the whole course.  "killed/occupied" is the floor a placement made dead per m^2 it covered.',
        "",
        "| group | task | n | usable floor covered | usable floor killed | killed / covered | killed by floor-lying / floor-standing / raised poses | killed by rescue stages (share) |",
        "|---|---|---:|---:|---:|---:|---|---:|",
    ]
    for g in groups:
        for task in ("C", "B"):
            E = [e for e in eps if e["group"] == g and e["task"] == task]
            if not E:
                continue
            occ = [
                sum(s["lost_usable_m2"] - s["killed_m2"] for s in e["steps"]) for e in E
            ]
            kil = [sum(s["killed_m2"] for s in e["steps"]) for e in E]
            pk = collections.Counter()
            resc = 0.0
            for e in E:
                for s in e["steps"]:
                    pk[pose_kind(s)] += s["killed_m2"]
                    if s["arch"] in RESCUE:
                        resc += s["killed_m2"]
            tk = max(1e-9, sum(pk.values()))
            lines.append(
                f"| {g} | {task} | {len(E)} | {fmt(stx.mean(occ))} | {fmt(stx.mean(kil))} | {fmt(sum(kil) / max(1e-9, sum(occ)))} | "
                f"{fmt(pk['floor-lying'] / tk)} / {fmt(pk['floor-standing'] / tk)} / {fmt(pk['raised'] / tk)} | {fmt(resc / tk)} |"
            )
    lines.append("")
    # by rung and class, H vs X
    for task in ("C", "B"):
        lines += [
            f"### 2a. Killed usable floor by rung, Task {task} (m^2 per episode; share of the group's kill; kill per placement of the rung)",
            "",
            "| rung (shadow outcome) | H kill/ep | H share | H kill per placement | X kill/ep | X share | X kill per placement |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        rows = collections.defaultdict(lambda: {"H": [0.0, 0], "X": [0.0, 0]})
        nE = {}
        for g in ("H", "X"):
            E = [e for e in eps if e["group"] == g and e["task"] == task]
            nE[g] = len(E)
            for e in E:
                for s in e["steps"]:
                    r = rows[arch_kind(s)][g]
                    r[0] += s["killed_m2"]
                    r[1] += 1
        totH = sum(v["H"][0] for v in rows.values()) or 1e-9
        totX = sum(v["X"][0] for v in rows.values()) or 1e-9
        for k, v in sorted(
            rows.items(), key=lambda kv: -(kv[1]["H"][0] / totH + kv[1]["X"][0] / totX)
        ):
            if v["H"][0] / totH < 0.02 and v["X"][0] / totX < 0.02:
                continue
            lines.append(
                f"| {k} | {fmt(v['H'][0] / max(1, nE['H']))} | {fmt(v['H'][0] / totH)} | {fmt(v['H'][0] / max(1, v['H'][1]), 3)} | "
                f"{fmt(v['X'][0] / max(1, nE['X']))} | {fmt(v['X'][0] / totX)} | {fmt(v['X'][0] / max(1, v['X'][1]), 3)} |"
            )
        lines.append("")
        lines += [
            f"### 2b. Killed usable floor by item class and pose, Task {task}",
            "",
            "| class / pose | H kill/ep | H share | X kill/ep | X share |",
            "|---|---:|---:|---:|---:|",
        ]
        rows = collections.defaultdict(lambda: {"H": 0.0, "X": 0.0})
        for g in ("H", "X"):
            for e in eps:
                if e["group"] != g or e["task"] != task:
                    continue
                for s in e["steps"]:
                    rows[(s["cls"].split("-")[0], pose_kind(s))][g] += s["killed_m2"]
        totH = sum(v["H"] for v in rows.values()) or 1e-9
        totX = sum(v["X"] for v in rows.values()) or 1e-9
        for k, v in sorted(
            rows.items(), key=lambda kv: -(kv[1]["H"] / totH + kv[1]["X"] / totX)
        ):
            if v["H"] / totH < 0.02 and v["X"] / totX < 0.02:
                continue
            lines.append(
                f"| {k[0]} / {k[1]} | {fmt(v['H'] / max(1, nE['H']))} | {fmt(v['H'] / totH)} | {fmt(v['X'] / max(1, nE['X']))} | {fmt(v['X'] / totX)} |"
            )
        lines.append("")
    # geometry of the kill
    lines += [
        "### 2c. The geometry of the killed strips (share of killed area)",
        "",
        "| group | task | narrow in y (lies along x) / narrow in x | bounded wall-box / box-box / wall-wall | relative to the new box: front (door side) / back / side / apart | width <0.1 / .1-.2 / .2-.3 / .3-.45 / >.45 |",
        "|---|---|---|---|---|---|",
    ]
    for g in groups:
        for task in ("C", "B"):
            E = [e for e in eps if e["group"] == g and e["task"] == task]
            if not E:
                continue
            c = collections.Counter()
            for e in E:
                for s in e["steps"]:
                    d = s.get("killed_desc") or {}
                    for k in (
                        "runs_x",
                        "runs_y",
                        "bound_wall_box",
                        "bound_box_box",
                        "bound_wall_wall",
                    ):
                        c[k] += d.get(k, 0.0)
                    for k, v in (d.get("width_hist") or {}).items():
                        c["w" + k] += v
                    for k, v in (s.get("killed_where") or {}).items():
                        c["at_" + k] += v
            t = max(1e-9, c["runs_x"] + c["runs_y"])
            tw = max(
                1e-9, sum(c["at_" + k] for k in ("front", "back", "side", "apart"))
            )
            wk = ["w0-0.1", "w0.1-0.2", "w0.2-0.3", "w0.3-0.45", "w0.45-9"]
            lines.append(
                f"| {g} | {task} | {fmt(c['runs_x'] / t)} / {fmt(c['runs_y'] / t)} | "
                f"{fmt(c['bound_wall_box'] / t)} / {fmt(c['bound_box_box'] / t)} / {fmt(c['bound_wall_wall'] / t)} | "
                + " / ".join(
                    fmt(c["at_" + k] / tw) for k in ("front", "back", "side", "apart")
                )
                + " | "
                + " / ".join(fmt(c[k] / t) for k in wk)
                + " |"
            )
    lines.append("")
    # ---------------------------------------------------------------- 3
    lines += [
        '## 3. The step that takes the last usable floor ("floor gone")',
        "",
        "The first step after which no container keeps 0.26 m^2 of usable floor (one window).  Fill and floor coverage at that step; what the step was.",
        "",
        "| group | task | n (floor gone / all) | fill at floor-gone | floor covered at floor-gone | placements after floor-gone | items short / over | rung of the step (top 4) | pose (lying / standing / raised) | shadow outcome / rescue |",
        "|---|---|---|---:|---:|---:|---:|---|---|---|",
    ]
    for g in groups:
        for task in ("C", "B"):
            E = [e for e in eps if e["group"] == g and e["task"] == task]
            if not E:
                continue
            fills, cov, after, mg = [], [], [], []
            rung = collections.Counter()
            pose = collections.Counter()
            sh = collections.Counter()
            for e in E:
                st = e["steps"]
                uf = [s["usable_floor_m2"] for s in st]
                gone = next(
                    (i for i in range(len(st)) if all(u < 0.26 for u in uf[i:])), None
                )
                if gone is None:
                    continue
                s = st[gone]
                fills.append(s["fill"])
                cov.append(1.0 - s["free_m2"] / e["floor_m2"])
                after.append(len(st) - gone - 1)
                mg.append(e["margin"])
                rung[s["arch"]] += 1
                pose[pose_kind(s)] += 1
                sh[
                    "rescue" if s["arch"] in RESCUE else (s.get("shadow") or "none")
                ] += 1
            if not fills:
                continue
            lines.append(
                f"| {g} | {task} | {len(fills)} / {len(E)} | {fmt(stx.median(fills))} | {fmt(stx.median(cov))} | {stx.median(after):.0f} | {stx.mean(mg):+.1f} | "
                + ", ".join(f"{k} {v}" for k, v in rung.most_common(4))
                + " | "
                + f"{pose['floor-lying']} / {pose['floor-standing']} / {pose['raised']} | "
                + ", ".join(f"{k} {v}" for k, v in sh.most_common(4))
                + " |"
            )
    lines.append("")
    open(f"{HERE}/strip_stats.md", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
